import { ApiProperty } from '@nestjs/swagger';
import { IDebtorFocusNote } from '@verichron/contracts';

export class DebtorFocusNoteDto implements IDebtorFocusNote {
  @ApiProperty({ description: "Unique identifier for the note", example: 'note-1a2b3c4d-e5f6-7a8b-9c0d-1e2f3a4b5c6d' })
  id: string;

  @ApiProperty({ description: "Content of the note", example: 'Debtor called, confirmed new payment plan effective next month.' })
  content: string;

  @ApiProperty({ description: "Timestamp of when the note was created", example: '2023-11-20T10:15:00.000Z' })
  createdAt: Date;

  @ApiProperty({ description: "ID of the user who created the note", example: 'user-789' })
  createdBy: string;

  @ApiProperty({ description: "Name of the user who created the note", example: 'Jane Smith' })
  createdByName: string;

  @ApiProperty({ description: "True if the note was generated by the system, false if by a user", example: false })
  isSystemGenerated: boolean;

  @ApiProperty({ description: "Optional: ID of the debt related to this note", example: 'debt-987', nullable: true })
  debtId: string | null;
}