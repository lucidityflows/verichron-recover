import { IsNotEmpty, IsNumber, IsString, IsOptional, IsObject, Min } from 'class-validator';
import type { ProcessRefundPayload } from '@verichron/contracts';

/**
 * Process Refund DTO
 *
 * Internal DTO for processing refunds through a gateway.
 * This is NOT exposed as a public API endpoint - refunds are initiated
 * through the transactions service.
 *
 * Contains all necessary information for gateway refund processing.
 */
export class ProcessRefundDto implements ProcessRefundPayload {
  /**
   * Refund amount in dollars (will be converted to cents for Stripe)
   */
  @IsNotEmpty({ message: 'amount is required' })
  @IsNumber({}, { message: 'amount must be a number' })
  @Min(0.01, { message: 'amount must be at least $0.01' })
  amount: number;

  /**
   * Original gateway transaction ID to refund
   * (e.g., Stripe charge ID or payment intent ID)
   */
  @IsNotEmpty({ message: 'originalGatewayTransactionId is required' })
  @IsString({ message: 'originalGatewayTransactionId must be a string' })
  originalGatewayTransactionId: string;

  /**
   * Idempotency key to prevent duplicate refunds
   * Should be a UUID generated by the transactions service
   */
  @IsNotEmpty({ message: 'idempotencyKey is required' })
  @IsString({ message: 'idempotencyKey must be a string' })
  idempotencyKey: string;

  /**
   * Optional metadata to attach to the refund
   * Useful for tracking refund reason, transaction ID, etc.
   */
  @IsOptional()
  @IsObject({ message: 'metadata must be an object' })
  metadata?: Record<string, any>;
}
