import { IsNotEmpty, IsNumber, IsString, IsOptional, IsObject, Min } from 'class-validator';
import type { ProcessPaymentPayload } from '@verichron/contracts';

/**
 * Process Payment DTO
 *
 * Internal DTO for processing payments through a gateway.
 * This is NOT exposed as a public API endpoint - payments are initiated
 * through the transactions service.
 *
 * Contains all necessary information for gateway payment processing.
 */
export class ProcessPaymentDto implements ProcessPaymentPayload {
  /**
   * Payment amount in dollars (will be converted to cents for Stripe)
   */
  @IsNotEmpty({ message: 'amount is required' })
  @IsNumber({}, { message: 'amount must be a number' })
  @Min(0.01, { message: 'amount must be at least $0.01' })
  amount: number;

  /**
   * Currency code (ISO 4217)
   * @default 'usd'
   */
  @IsOptional()
  @IsString({ message: 'currency must be a string' })
  currency?: string;

  /**
   * Tokenized payment method (e.g., Stripe payment method ID or token)
   * Never contains raw card data
   */
  @IsNotEmpty({ message: 'paymentMethodToken is required' })
  @IsString({ message: 'paymentMethodToken must be a string' })
  paymentMethodToken: string;

  /**
   * Idempotency key to prevent duplicate charges
   * Should be a UUID generated by the transactions service
   */
  @IsNotEmpty({ message: 'idempotencyKey is required' })
  @IsString({ message: 'idempotencyKey must be a string' })
  idempotencyKey: string;

  /**
   * Optional metadata to attach to the payment
   * Useful for tracking transaction ID, debt ID, etc.
   */
  @IsOptional()
  @IsObject({ message: 'metadata must be an object' })
  metadata?: Record<string, any>;
}
