/**
 * Content format enumeration for collector notes
 * Defines supported rich text formats
 */
export enum ContentFormat {
  /**
   * Plain text without formatting
   */
  PLAINTEXT = 'PLAINTEXT',

  /**
   * HTML formatted content
   */
  HTML = 'HTML',

  /**
   * Markdown formatted content
   */
  MARKDOWN = 'MARKDOWN',
}
