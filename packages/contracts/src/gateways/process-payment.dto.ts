/**
 * Process Payment DTO
 * 
 * Internal DTO used by the transactions service to request payment processing.
 * This is NOT a REST endpoint DTO - it's for internal service-to-service communication.
 * No validation decorators needed as validation happens at the REST layer.
 */
export interface ProcessPaymentDto {
  /**
   * Payment amount in USD (or specified currency)
   */
  amount: number;

  /**
   * Tokenized payment method from client-side tokenization (e.g., Stripe.js)
   * NEVER contains raw card data
   */
  paymentMethodToken: string;

  /**
   * Unique idempotency key to prevent duplicate charges
   * Generated by the transactions service
   */
  idempotencyKey: string;

  /**
   * Currency code (ISO 4217)
   * @default 'usd'
   */
  currency?: string;

  /**
   * Optional metadata to attach to the payment
   */
  metadata?: Record<string, any>;
}